/* Writes the CMS seed migration from the built-in catalogue, so the database
   starts with exactly the prices the site shows today, all published.
     bun scripts/cms-seed.ts
   Re-run only before the seed migration has been applied anywhere; after
   that, prices are edited in the admin, not here. */
import { writeFileSync } from 'node:fs'
import { SERVICES, BOOKING_DEFAULTS } from '../app/content/services'

const q = (v: unknown) => (v == null ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`)
const out = ['-- Generated by scripts/cms-seed.ts from app/content/services.ts. Initial content, all published.', '']

SERVICES.forEach((s, i) => {
  out.push(`INSERT INTO packages (id, tier, name, tag, price, deposit_pct, hours, coverage, delivery, delivery_unit, live, blurb, includes, notes, sort, published, updated_by) VALUES (${[
    s.id, s.tier, s.name, s.tag, s.price, Math.round(s.dep * 100), s.hours, s.cov, s.delivery, s.deliveryUnit,
    s.live ? 1 : 0, s.blurb, JSON.stringify(s.includes), JSON.stringify(s.notes), i, 1, 'seed',
  ].map(q).join(', ')});`)
  s.addons.forEach((a, j) => {
    out.push(`INSERT INTO addons (package_id, id, name, unit, type, price, max, description, affects, sort) VALUES (${[
      s.id, a.id, a.name, a.unit, a.type, a.price, a.max, a.d, a.affects, j,
    ].map(q).join(', ')});`)
  })
  out.push('')
})
out.push(`INSERT INTO settings (key, value, updated_by) VALUES ('booking', ${q(JSON.stringify(BOOKING_DEFAULTS))}, 'seed');`, '')

writeFileSync(new URL('../server/database/migrations/0002_seed.sql', import.meta.url), out.join('\n'))
console.log('wrote server/database/migrations/0002_seed.sql')
